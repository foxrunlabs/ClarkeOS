#define _IO_H


/*==============================================================================
  Macros
==============================================================================*/

/*==============================================================================
  outb - output a byte to a port
--------------------------------------------------------------------------------
  Output a byte to a port using inline assembly.
==============================================================================*/

#define outb(port, value) __asm__ __volatile__ ("outb %b0, %w1" :: "a" (value), "Nd" (port))


#endif /* _IO_H */
